// singleplayer/ui/equipment-language.js
function potentialLabelRef(potential) {
  const id = potential.localeId || equipment_default.potentialNames[potential.name];
  return id ? { $entity: "potentials", id, field: "name" } : potential.name;
}
function affixLabelRef(affix) {
  return {
    $entity: "affixes",
    id: affix.tier === "legacy" ? "legacy" : affix.group + "." + affix.tier,
    field: "name",
  };
}
function affixEffectRef(affix) {
  const key =
    affix.tier === "legacy"
      ? "affix.legacy." + (affix.type === 1002 ? "KillXP" : "MagicFind")
      : "affix.effect." + affix.group;
  return {
    $text: key,
    params: {
      val: affix.low,
      vallow: affix.low,
      valhigh: affix.high,
      dura: affix.duration,
      rate: affix.rate,
    },
  };
}
var potentialStatKey = (key) => equipment_default.potentialStats[key];
export { affixEffectRef, affixLabelRef, potentialLabelRef, potentialStatKey };

